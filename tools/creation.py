"""Tool Creation Agent: need description + API doc -> validated, registered tool.

LLM contract: llm.generate(prompt, temperature=0.2, max_tokens=1500) -> str
"""
from __future__ import annotations

import json
import re
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

from tools import sandbox
from tools.base import ToolSpec

NAME_RE = re.compile(r"^[a-z][a-z0-9_]{2,40}$")

PROMPT = """You write small Python tool functions for a biomedical research agent.

NEED:
{need}

API DOCUMENTATION:
{doc}

Rules:
- Import only: requests, json, re.
- Define exactly one top-level function run(...) that takes keyword arguments and returns a JSON-serialisable dict.
- Every requests call MUST pass timeout=15.
- If nothing is found, raise LookupError with a short message.
- No file access, no eval/exec, no attributes that start with double underscores, no printing.

Reply in EXACTLY this format and nothing else:
NAME: <snake_case_tool_name>
DESCRIPTION: <one sentence describing what the tool returns>
PARAMS: <one-line JSON object mapping each argument name to a type string, e.g. {{"gene": "string"}}>
TEST_ARGS: <one-line JSON object with a real example call>
CODE:
```python
<the code>
```
{feedback}"""


@dataclass
class CreationReport:
    need: str
    passed: bool = False
    tool_name: str | None = None
    attempts: int = 0
    error: str | None = None
    code_path: str | None = None
    spec_path: str | None = None
    handwritten: bool = False
    log: list[dict] = field(default_factory=list)


def parse_llm_output(text: str) -> dict:
    """Extract NAME, DESCRIPTION, PARAMS, TEST_ARGS and CODE; raise ValueError if malformed."""

    def field_(label: str) -> str:
        m = re.search(rf"^{label}:\s*(.+)$", text, re.MULTILINE)
        if not m:
            raise ValueError(f"missing {label}")
        return m.group(1).strip()

    code = re.search(r"CODE:\s*```(?:python)?\s*\n(.*?)```", text, re.DOTALL)
    if not code:
        raise ValueError("missing CODE block")
    try:
        params = json.loads(field_("PARAMS"))
        test_args = json.loads(field_("TEST_ARGS"))
    except json.JSONDecodeError as e:
        raise ValueError(f"PARAMS/TEST_ARGS are not valid JSON: {e}") from e
    if not isinstance(params, dict) or not isinstance(test_args, dict):
        raise ValueError("PARAMS and TEST_ARGS must be JSON objects")
    return {
        "name": field_("NAME"),
        "description": field_("DESCRIPTION"),
        "params": params,
        "test_args": test_args,
        "code": code.group(1).strip() + "\n",
    }

def _schema(params: dict) -> dict:
    return {
        "type": "object",
        "properties": {k: {"type": str(v)} for k, v in params.items()},
        "required": list(params),
    }


def _validate(parsed: dict, registry, expect_keys: list[str] | None, timeout: int) -> str | None:
    """Return an error message, or None when the candidate tool is valid."""
    name = parsed["name"]
    if not NAME_RE.match(name):
        return f"NAME must be snake_case, 3-41 chars; got {name!r}"
    if registry is not None and name in registry.names():
        return f"a tool named {name} already exists; choose a different NAME"
    problems = sandbox.check_code(parsed["code"], expected_params=list(parsed["params"]))
    if problems:
        return "static check failed: " + "; ".join(problems)
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / f"{name}.py"
        path.write_text(parsed["code"])
        res = sandbox.run_file(str(path), parsed["test_args"], timeout=timeout)
    if not res["ok"]:
        return f"test call failed: {res['error']}"
    if not res["data"]:
        return "test call returned an empty result"
    if expect_keys:
        missing = [k for k in expect_keys if k not in res["data"]]
        if missing:
            return f"test call result is missing keys {missing}; got {list(res['data'])}"
    return None


def _install(parsed: dict, registry, generated_dir: str, handwritten: bool) -> tuple[str, str]:
    out = Path(generated_dir)
    out.mkdir(parents=True, exist_ok=True)
    code_path = out / f"{parsed['name']}.py"
    header = (
        "# AUTO-GENERATED by tools/creation.py\n"
        if not handwritten
        else "# HAND-WRITTEN fallback registered via tools/creation.py\n"
    )
    code_path.write_text(header + parsed["code"])
    spec = ToolSpec(parsed["name"], parsed["description"], _schema(parsed["params"]), "generated")
    if registry is not None:
        registry.register(spec, str(code_path))
    spec_path = out / f"{parsed['name']}.json"
    if registry is None:
        spec_path.write_text(json.dumps({**spec.to_dict(), "code_path": str(code_path)}, indent=2))
    return str(code_path), str(spec_path)


def create_tool(
    need: str,
    doc_path: str,
    llm,
    registry=None,
    expect_keys: list[str] | None = None,
    generated_dir: str = "tools/generated",
    max_retries: int = 2,
    timeout: int = 20,
) -> CreationReport:
    """Ask the LLM for a tool, validate it, retry with error feedback, then register it."""
    report = CreationReport(need=need)
    doc = Path(doc_path).read_text(encoding="utf-8")
    feedback = ""
    for attempt in range(1, max_retries + 2):
        report.attempts = attempt
        prompt = PROMPT.format(need=need, doc=doc, feedback=feedback)
        raw = llm.generate(prompt, temperature=0.2, max_tokens=1500)
        try:
            parsed = parse_llm_output(raw)
        except ValueError as e:
            err = f"could not parse your reply: {e}"
        else:
            err = _validate(parsed, registry, expect_keys, timeout)
            if err is None:
                report.passed = True
                report.tool_name = parsed["name"]
                report.code_path, report.spec_path = _install(parsed, registry, generated_dir, False)
                report.log.append({"attempt": attempt, "ok": True})
                return report
            report.tool_name = parsed["name"]
        report.error = err
        report.log.append({"attempt": attempt, "ok": False, "error": err})
        feedback = f"\nYour previous attempt failed: {err}\nFix it and reply in the same format."
    return report


def register_handwritten(
    code_path: str,
    name: str,
    description: str,
    params: dict,
    test_args: dict,
    registry=None,
    expect_keys: list[str] | None = None,
    generated_dir: str = "tools/generated",
) -> CreationReport:
    """Fallback: register a hand-written tool using the SAME checks as generated ones.

    The report must say this tool was written by hand, not by the Tool Creation Agent.
    """
    report = CreationReport(need=f"handwritten:{name}", handwritten=True, tool_name=name, attempts=1)
    parsed = {
        "name": name,
        "description": description,
        "params": params,
        "test_args": test_args,
        "code": Path(code_path).read_text(encoding="utf-8"),
    }
    err = _validate(parsed, registry, expect_keys, 20)
    if err:
        report.error = err
        return report
    report.passed = True
    report.code_path, report.spec_path = _install(parsed, registry, generated_dir, True)
    return report